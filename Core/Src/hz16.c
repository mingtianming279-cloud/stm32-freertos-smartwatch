const uint16_t hz16_count = 30;

const hz16_glyph_t *hz16_lookup(const char *utf8)
{
	uint16_t i;
	if ((utf8 == 0) || (utf8[0] == '\0')) return 0;

	for (i = 0u; i < hz16_count; i++)
	{
		const char *p = hz16_table[i].utf8;
		if ((p[0] == utf8[0]) && (p[1] == utf8[1]) && (p[2] == utf8[2]))
		{
			return &hz16_table[i];
		}
	}
	return 0;
}
